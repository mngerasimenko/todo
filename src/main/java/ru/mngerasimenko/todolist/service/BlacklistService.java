package ru.mngerasimenko.todolist.service;

/**
 * Сервис фильтрации нецензурной лексики в текстовых полях, попадающих в общий
 * пользовательский словарь (Server R-6 — глобальные подсказки).
 * <p>
 * Источник истины — {@code src/main/resources/suggestion_blacklist.txt} (RU+EN корни).
 * Расширяется по жалобам через PR; runtime-расширение не предусмотрено намеренно
 * (любая live-правка списка — это изменение списка модерации, которое должно
 * пройти review).
 */
public interface BlacklistService {

    /**
     * @param text сырой текст из пользовательского ввода (без какой-либо обработки)
     * @return true, если после нормализации (нижний регистр + де-обфускация «о→0», «и→1»
     * и т.п. + удаление не-буквенных символов) текст содержит любой корень из blacklist'а
     */
    boolean contains(String text);
}
