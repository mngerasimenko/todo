package ru.mngerasimenko.todolist.featureflags;

/**
 * Сколько живёт ручное переключение флага через {@code PUT /api/admin/flags/{name}/{value}}.
 *
 * <p>{@link #PROCESS} — только до ближайшего рестарта. Для флагов ЗАЩИТЫ это не недостаток,
 * а свойство: снятая на время разбирательства защита обязана восстановиться сама, даже если
 * про неё забыли.
 *
 * <p>{@link #PERSISTENT} — переживает рестарт, деплой и пересоздание контейнеров, потому что
 * хранится в БД. Для флагов ФИЧ процессное поведение было прямо вредным: аварийно выключенная
 * функция возвращалась пользователям сама, причём в непредсказуемый момент — staging
 * передеплоивается на каждый merge в master.
 */
public enum OverrideLifetime {
    PROCESS,
    PERSISTENT
}
