package ru.mngerasimenko.todolist.featureflags;

/**
 * Кто исполняет флаг — сервер или клиентское приложение.
 *
 * <p>{@link #SERVER} — флаг влияет на поведение самого сервера и наружу не отдаётся.
 * Значения таких флагов видны только супер-админу через {@code GET /api/admin/flags}:
 * набор серверных выключателей с описаниями — это операционная карта сервиса,
 * и раздавать её в каждое установленное приложение незачем.
 *
 * <p>{@link #CLIENT} — флаг исполняет приложение. Сервер его только хранит и
 * транслирует в {@code GET /api/status}, откуда клиент забирает значения при
 * старте. Переключаются такие флаги тем же {@code PUT /api/admin/flags/{name}/{value}},
 * что и серверные, — пульт один.
 */
public enum Audience {
    SERVER,
    CLIENT
}
