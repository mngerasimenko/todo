#!/usr/bin/env bash
# Общая отправка в VK для старых скриптов мониторинга: server-monitor.sh,
# stats-report.sh, vk-bot.sh. Подключается через `source` рядом со скриптом.
#
# Зачем отдельный файл, а не три правки на месте:
#
#   1. Все трое звали `curl -d access_token=…`, то есть токен сообщества был
#      виден в `ps` любому локальному пользователю: /proc на проде без hidepid,
#      а окно видимости — до 15 секунд на вызов. Теперь секрет уезжает конфигом
#      на stdin (`curl -K -`), как это уже делает portfolio-monitor.sh.
#   2. Ни один из трёх не смотрел, что ответил VK. Протухший токен, забаненное
#      сообщество и заблокированный диалог давали тишину, неотличимую от
#      исправного канала, — а тишина здесь и означает «всё хорошо».
#
# portfolio-monitor.sh свою отправку сюда не переносит намеренно: она вплетена в
# состояние канала, маячки дед-мэна и обрезку длинных сообщений, и вынос значил
# бы правку сторожа ради единообразия. Если будете сводить их в одно — начинать
# отсюда, поведение совпадает построчно.

# Значение внутри конфига curl берётся в кавычки — экранируем слэш и кавычку.
# Перевод строки и возврат каретки ВЫРЕЗАЕМ: конфиг curl разбирается построчно,
# и значение с переводом строки закрывает кавычку, а следующая строка читается
# как ЕЩЁ ОДНА опция curl (`output = …` пишет файл от root). Сюда попадают не
# только локальные значения: адрес и сессионный ключ Long Poll приезжают из сети.
vk_cfg_escape() {
  local s="$1"
  s="${s//$'\n'/}"
  s="${s//$'\r'/}"
  s="${s//\\/\\\\}"
  s="${s//\"/\\\"}"
  printf '%s' "$s"
}

# Токен не должен попасть в лог: curl умеет вернуть переданный ему URL в тексте
# ошибки, а ответ VK — процитировать часть запроса.
vk_redact() {
  local s="$1"
  [ -n "${VK_TOKEN:-}" ] && s="${s//${VK_TOKEN}/<VK_TOKEN>}"
  printf '%s' "$s"
}

# Пишем в stderr: у cron-скриптов он уходит в их собственный лог, у бота под
# systemd — в journal. Своего файла лога эта библиотека не заводит, чтобы не
# появилось четвёртое место, куда никто не смотрит.
vk_log() {
  printf '%s [vk] %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$(vk_redact "$1")" >&2
}

# Обрезка до N байт с отрезанием недописанного символа. Под cron локаль C, и в
# ней bash считает и режет именно байты: разрез посреди кириллической пары
# оставил бы незавершённую последовательность, а битый UTF-8 VK отвергает
# целиком — сообщение пропало бы вместо того, чтобы прийти обрезанным.
# `iconv -c` выбрасывает недописанный хвост; там, где iconv недоступен, снимаем
# последний символ шаблоном: потеря одного знака дешевле потерянного сообщения.
vk_utf8_cut() {
  local s="${1:0:$2}" out
  out="$(printf '%s' "$s" | iconv -c -f UTF-8 -t UTF-8 2>/dev/null)"
  if [ -z "$out" ] && [ -n "$s" ]; then
    out="$(printf '%s' "$s" | LC_ALL=C sed -E 's/[\xC0-\xFF][\x80-\xBF]{0,2}$//')"
  fi
  printf '%s' "$out"
}

# Ответ считаем успешным, только если в нём есть "response" и нет "error".
# jq не зовём — на части хостов его нет. Одного вхождения "response" мало:
# слово встречается и в телах ошибок VK.
vk_response_ok() {
  printf '%s' "$1" | grep -q '"response"' && ! printf '%s' "$1" | grep -q '"error'
}

# Общая часть конфига curl для вызова метода API.
vk_common_lines() {
  printf 'url = "https://api.vk.com/method/%s"\n' "$(vk_cfg_escape "$1")"
  printf 'data-urlencode = "access_token=%s"\n' "$(vk_cfg_escape "${VK_TOKEN:-}")"
  printf 'data-urlencode = "v=%s"\n' "$(vk_cfg_escape "${VK_API_VERSION:-5.199}")"
}

# Вызов метода VK: vk_api_post <метод> [имя=значение ...]. Печатает тело ответа,
# код возврата — код curl: сеть легла и VK отверг запрос — разные диагнозы, и
# вызывающий обязан их различать, иначе в журнал идёт «VK отверг» на пустом теле.
vk_api_post() {
  local method="$1"; shift
  local p
  {
    vk_common_lines "$method"
    for p in "$@"; do
      printf 'data-urlencode = "%s=%s"\n' "${p%%=*}" "$(vk_cfg_escape "${p#*=}")"
    done
  } | curl -sS -m "${VK_TIMEOUT:-15}" -K - 2>/dev/null
}

# GET по готовому URL — для опроса Long Poll, где в URL едет сессионный ключ.
# Ключу в argv делать нечего ровно по той же причине, что и токену.
vk_get_url() {
  printf 'url = "%s"\n' "$(vk_cfg_escape "$1")" \
    | curl -sS -m "${2:-${VK_TIMEOUT:-15}}" -K - 2>/dev/null
}

# Отправка сообщения владельцу. 0 — VK подтвердил приём, 1 — не подтвердил, и
# тогда причина уже в stderr. Вызывающий обязан различать эти два исхода: именно
# на этом месте канал молчал годом раньше.
vk_send_message() {
  local text peer="${2:-${VK_PEER_ID:-}}" file resp rc cut l
  # Текст тоже через redact: в сообщение попадает вывод чужих команд (логи
  # приложения у бота), и токену там делать нечего — диалог владельца хранится
  # в VK и переживёт нас.
  text="$(vk_redact "$1")"
  if [ -z "${VK_TOKEN:-}" ] || [ -z "$peer" ]; then
    vk_log "НЕТ УЧЁТКИ (нет токена или адресата): сообщение не ушло — <<$(printf '%s' "$text" | head -c 120)>>"
    return 1
  fi
  # VK принимает до 4096 символов. Отвергнутое по длине сообщение — потерянное
  # сообщение: сводка со списком новых пользователей ничем не ограничена сверху,
  # и в день массовых регистраций она пропала бы целиком. Режем сначала по
  # границе строки (так текст остаётся читаемым), а недобранный остаток бюджета
  # дозаполняем хвостом — иначе текст без переводов строки, то есть ответ на
  # /logs с одной длинной строкой лога, уезжал в ВК одним заголовком.
  if [ "${#text}" -gt 3500 ]; then
    # В лог идёт только начало: там же оказываются имена пользователей из
    # суточной сводки, а /var/log читают все локальные учётки хоста.
    vk_log "сообщение длиной ${#text} обрезано до 3400, начало: <<$(vk_utf8_cut "$text" 200)>>"
    cut=""
    while IFS= read -r l; do
      [ $(( ${#cut} + ${#l} + 1 )) -gt 3400 ] && break
      cut="${cut}${l}"$'\n'
    done <<< "$text"
    # Осталось место — добираем началом невлезшей части. Граница символа здесь
    # обязательна: под cron локаль C, bash режет байты, а битый UTF-8 VK
    # отвергает целиком.
    if [ "${#cut}" -lt 3400 ]; then
      cut="${cut}$(vk_utf8_cut "${text:${#cut}}" $(( 3400 - ${#cut} )))"
    fi
    text="${cut}… (обрезано)"
  fi
  # Текст многострочный, а в конфиге curl перевод строки внутри значения не
  # живёт — поэтому сообщение едет отдельным файлом (0600 от mktemp).
  file="$(mktemp "${TMPDIR:-/tmp}/vk-msg.XXXXXX" 2>/dev/null)"
  if [ -z "$file" ]; then
    vk_log "не смог создать временный файл в ${TMPDIR:-/tmp} — сообщение не ушло"
    return 1
  fi
  printf '%s' "$text" > "$file"
  # random_id — в пределах int32: так его описывает часть документации VK.
  resp="$( { vk_common_lines messages.send
             printf 'data-urlencode = "peer_id=%s"\n' "$(vk_cfg_escape "$peer")"
             printf 'data-urlencode = "random_id=%s"\n' "$(( RANDOM * 32768 + RANDOM ))"
             printf 'data-urlencode = "message@%s"\n' "$(vk_cfg_escape "$file")"
           } | curl -sS -m "${VK_TIMEOUT:-15}" -K - 2>/dev/null )"
  rc=$?
  rm -f "$file"
  if [ "$rc" -ne 0 ]; then
    vk_log "curl упал (rc=${rc}) — сообщение не ушло"
    return 1
  fi
  if vk_response_ok "$resp"; then
    return 0
  fi
  vk_log "VK отверг отправку: $(printf '%s' "$resp" | head -c 200)"
  return 1
}
